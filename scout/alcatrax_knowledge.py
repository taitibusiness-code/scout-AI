def _by_id(items):
    return {item.id: item for item in items}


def capability_by_id(capability_id: str) -> Capability | None:
    return _by_id(CAPABILITIES).get(capability_id)


def project_by_id(project_id: str) -> PastProject | None:
    return _by_id(PAST_PROJECTS).get(project_id)


def project_by_identifier(identifier: str) -> PastProject | None:
    return project_by_id(identifier) or next((p for p in PAST_PROJECTS if p.client_name == identifier), None)


def pattern_by_id(pattern_id: str) -> SolutionPattern | None:
    return _by_id(SOLUTION_PATTERNS).get(pattern_id)


def capability_exists(capability_id: str) -> bool:
    return capability_by_id(capability_id) is not None


def project_exists(identifier: str) -> bool:
    return project_by_identifier(identifier) is not None


def pattern_exists(pattern_id: str) -> bool:
    return pattern_by_id(pattern_id) is not None


def pattern_includes_capability(pattern_id: str, capability_id: str) -> bool:
    pattern = pattern_by_id(pattern_id)
    return bool(pattern and capability_id in pattern.capability_ids)


def project_demonstrates_capability(project_identifier: str, capability_id: str) -> bool:
    project = project_by_identifier(project_identifier)
    return bool(project and capability_id in project.capabilities_used)


def project_supports_pattern(project_identifier: str, pattern_id: str) -> bool:
    project = project_by_identifier(project_identifier)
    pattern = pattern_by_id(pattern_id)
    return bool(project and pattern and pattern_id in project.solution_pattern_ids and project.id in pattern.relevant_project_ids)


def projects_for_pattern(pattern_id: str) -> list[PastProject]:
    pattern = pattern_by_id(pattern_id)
    if not pattern:
        return []
    return [project_by_id(project_id) for project_id in pattern.relevant_project_ids if project_by_id(project_id)]


def patterns_for_problem(problem_tag: str) -> list[SolutionPattern]:
    return [pattern for pattern in SOLUTION_PATTERNS if problem_tag in pattern.problem_tags]


def capabilities_for_problem(problem_tag: str) -> list[Capability]:
    return [capability for capability in CAPABILITIES if problem_tag in capability.solves]


def reference_projects_for_industry(industry: str) -> list[PastProject]:
    return [project for project in PAST_PROJECTS if project.industry == industry]


def catalogue_integrity_errors() -> list[str]:
    """Return deterministic errors; tests call this to protect curated data."""
    errors: list[str] = []
    for label, items in (("capability", CAPABILITIES), ("project", PAST_PROJECTS), ("pattern", SOLUTION_PATTERNS)):
        ids = [item.id for item in items]
        if len(ids) != len(set(ids)):
            errors.append(f"duplicate {label} IDs")
    for project in PAST_PROJECTS:
        for capability_id in project.capabilities_used:
            if not capability_exists(capability_id):
                errors.append(f"project {project.id} references unknown capability {capability_id}")
        for pattern_id in project.solution_pattern_ids:
            if not pattern_exists(pattern_id):
                errors.append(f"project {project.id} references unknown pattern {pattern_id}")
    for pattern in SOLUTION_PATTERNS:
        for capability_id in pattern.capability_ids:
            if not capability_exists(capability_id):
                errors.append(f"pattern {pattern.id} references unknown capability {capability_id}")
        for project_id in pattern.relevant_project_ids:
            if not project_by_id(project_id):
                errors.append(f"pattern {pattern.id} references unknown project {project_id}")
            elif not project_supports_pattern(project_id, pattern.id):
                errors.append(f"pattern {pattern.id} and project {project_id} are not mutually linked")
    return errors


def assert_catalogue_integrity() -> None:
    errors = catalogue_integrity_errors()
    if errors:
        raise ValueError("Alcatrax knowledge catalogue is invalid: " + "; ".join(errors))


def as_prompt_context() -> str:
    cap_lines = "\n".join(
        f"- {cap.id}: {cap.name} [{cap.maturity}] -- {cap.description}" for cap in CAPABILITIES
    )
    pattern_lines = "\n".join(
        f"- {pattern.id}: {pattern.name}; problems={', '.join(pattern.problem_tags)}; "
        f"capabilities={', '.join(pattern.capability_ids)}; projects={', '.join(pattern.relevant_project_ids)}"
        for pattern in SOLUTION_PATTERNS
    )
    project_lines = "\n".join(
        f"- {project.id}: {project.client_name} ({project.industry}); "
        f"capabilities={', '.join(project.capabilities_used) or 'unknown'}; "
        f"patterns={', '.join(project.solution_pattern_ids) or 'unknown'}"
        for project in PAST_PROJECTS
    )
    return (
        f"ALCATRAX CAPABILITIES:\n{cap_lines}\n\nALCATRAX SOLUTION PATTERNS:\n{pattern_lines}\n\n"
        f"ALCATRAX PAST PROJECTS:\n{project_lines}\n\n"
        "Choose only listed IDs. A project is proof only when it is listed for the chosen pattern and "
        "demonstrates the chosen capability. Leave any unsupported reference empty."
    )
