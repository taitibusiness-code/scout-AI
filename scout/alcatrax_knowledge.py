"""Alcatrax's curated, evidence-bounded knowledge brain.

This module is data maintained by Alcatrax, never generated by Scout. A
capability says what Alcatrax can offer; a solution pattern is a reusable
solution shape; a past project is proof only for the patterns/capabilities it
explicitly records. Unknown project detail intentionally remains unknown.
"""
from __future__ import annotations

from dataclasses import dataclass, field


MATURITY_STATES = ("proven", "demonstrated", "developing")


@dataclass(frozen=True)
class Capability:
    id: str
    name: str
    description: str
    solves: list[str]
    maturity: str = "developing"
    proof_notes: str = ""


@dataclass(frozen=True)
class SolutionPattern:
    """Reusable solution type, distinct from both a capability and a client."""
    id: str
    name: str
    description: str
    problem_tags: list[str]
    capability_ids: list[str]
    relevant_project_ids: list[str]


